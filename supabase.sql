create extension if not exists pgcrypto;

create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text not null unique,
 coins bigint not null default 0 check (coins >= 0),
 best_distance integer not null default 0,
 total_distance bigint not null default 0,
 highest_level integer not null default 1 check (highest_level between 1 and 300),
 selected_background text not null default 'city',
 selected_character text not null default 'runner',
 selected_obstacle_set text not null default 'classic',
 lives_level integer not null default 1 check (lives_level between 1 and 5),
 distance_level integer not null default 1 check (distance_level between 1 and 6),
 dash_level integer not null default 1 check (dash_level between 1 and 6),
 jump_level integer not null default 1 check (jump_level between 1 and 6),
 coin_level integer not null default 1 check (coin_level between 1 and 6),
 bonus_level integer not null default 1 check (bonus_level between 1 and 6),
 daily_login_streak integer not null default 0,
 last_login_reward date,
 last_quest_reset date,
 quest_distance integer not null default 0,
 quest_coins integer not null default 0,
 quest_games integer not null default 0,
 quest_distance_claimed boolean not null default false,
 quest_coins_claimed boolean not null default false,
 quest_games_claimed boolean not null default false,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create table if not exists public.inventory (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 item_type text not null check (item_type in ('background','character','obstacle')),
 item_id text not null,
 owned_at timestamptz not null default now(),
 unique(user_id,item_type,item_id)
);

create table if not exists public.run_history (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 mode text not null check (mode in ('infinite','level')),
 level_number integer,
 distance integer not null default 0,
 coins integer not null default 0,
 survived_seconds integer not null default 0,
 created_at timestamptz not null default now()
);

create table if not exists public.friends (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 friend_id uuid not null references public.profiles(id) on delete cascade,
 status text not null default 'accepted' check (status in ('pending','accepted','blocked')),
 created_at timestamptz not null default now(),
 unique(user_id,friend_id),
 check(user_id <> friend_id)
);

create table if not exists public.admin_gifts (
 id bigint generated by default as identity primary key,
 target_user uuid not null references public.profiles(id) on delete cascade,
 amount bigint not null check (amount > 0 and amount <= 1000000),
 created_by uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);

