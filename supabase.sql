returns table(
 username text,
 best_distance integer,
 highest_level integer
)
language sql
security definer
set search_path=public
as $$
 select p.username,p.best_distance,p.highest_level
 from public.profiles p
 order by p.best_distance desc,p.highest_level desc,p.username asc;
$$;

