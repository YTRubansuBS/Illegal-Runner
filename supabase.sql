create or replace function public.change_coins(amount bigint)
returns bigint language plpgsql security invoker as $$
declare b bigint;
begin update public.profiles set coins=greatest(0,coins+amount),updated_at=now() where id=auth.uid() returning coins into b; if b is null then raise exception 'Profile not found'; end if; return b; end;
$$;

create or replace function public.finish_run(p_mode text,p_level integer,p_distance integer,p_coins integer,p_seconds integer,p_highest_level integer)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare b integer; td bigint; c bigint; qd integer; qc integer; qg integer; hl integer;
begin
 update public.profiles
 set coins=coins+greatest(0,p_coins),
     best_distance=greatest(best_distance,greatest(0,p_distance)),
     total_distance=total_distance+greatest(0,p_distance),
     highest_level=greatest(highest_level,least(300,greatest(1,p_highest_level))),
     quest_distance=quest_distance+greatest(0,p_distance),
     quest_coins=quest_coins+greatest(0,p_coins),
     quest_games=quest_games+1,
     updated_at=now()
 where id=auth.uid()
 returning best_distance,total_distance,coins,quest_distance,quest_coins,quest_games,highest_level into b,td,c,qd,qc,qg,hl;
 if b is null then raise exception 'Profile not found'; end if;
 insert into public.run_history(user_id,mode,level_number,distance,coins,survived_seconds)
 values(auth.uid(),p_mode,nullif(p_level,0),greatest(0,p_distance),greatest(0,p_coins),greatest(0,p_seconds));
 return jsonb_build_object('coins',c,'best_distance',b,'total_distance',td,'highest_level',hl,'quest_distance',qd,'quest_coins',qc,'quest_games',qg);
end;
$$;

