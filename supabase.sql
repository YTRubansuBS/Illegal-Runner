create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,username) values(new.id,coalesce(new.raw_user_meta_data->>'username',split_part(new.email,'@',1))) on conflict(id) do nothing;
 return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.give_default_items()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.inventory(user_id,item_type,item_id) values (new.id,'background','city'),(new.id,'character','runner'),(new.id,'obstacle','classic') on conflict do nothing;
 return new;
end;
$$;
drop trigger if exists on_profile_created_items on public.profiles;
create trigger on_profile_created_items after insert on public.profiles for each row execute procedure public.give_default_items();

create or replace function public.change_coins(amount bigint)
returns bigint language plpgsql security invoker as $$
declare b bigint;
begin update public.profiles set coins=greatest(0,coins+amount),updated_at=now() where id=auth.uid() returning coins into b; if b is null then raise exception 'Profile not found'; end if; return b; end;
$$;

create or replace function public.finish_run(p_mode text,p_level integer,p_distance integer,p_coins integer,p_seconds integer)
returns jsonb language plpgsql security invoker as $$
declare b integer; qd integer; qc integer; qg integer;
begin
 update public.profiles set best_distance=greatest(best_distance,greatest(0,p_distance)),total_distance=total_distance+greatest(0,p_distance),quest_distance=quest_distance+greatest(0,p_distance),quest_coins=quest_coins+greatest(0,p_coins),quest_games=quest_games+1,updated_at=now() where id=auth.uid() returning best_distance,quest_distance,quest_coins,quest_games into b,qd,qc,qg;
 insert into public.run_history(user_id,mode,level_number,distance,coins,survived_seconds) values(auth.uid(),p_mode,nullif(p_level,0),greatest(0,p_distance),greatest(0,p_coins),greatest(0,p_seconds));
 return jsonb_build_object('best_distance',b,'quest_distance',qd,'quest_coins',qc,'quest_games',qg);
end;
$$;

create or replace function public.apply_admin_gift()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 update public.profiles set coins=coins+new.amount,updated_at=now() where id=new.target_user;
 return new;
end;
$$;
drop trigger if exists on_admin_gift on public.admin_gifts;
create trigger on_admin_gift after insert on public.admin_gifts for each row execute procedure public.apply_admin_gift();

